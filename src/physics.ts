/**
 * Физическая адекватность: как ведёт себя НАСТОЯЩИЙ игрок.
 *
 * Классическая ошибка кривых ботов: получив откидывание, они или продолжают
 * слать невозможные пакеты, или (что тоже плохо) замирают. Живой игрок в откате
 * НЕ отпускает клавиши — его тащит физика, а как только откат затухает, он
 * продолжает идти туда, куда шёл (всё ещё зажимая условный W).
 *
 * Поэтому обёртка при уроне/откидывании:
 *  - НЕ трогает управление (кнопки игрока остаются зажатыми);
 *  - НЕ ставит пауз и не «переживает» откат бездействием;
 *  - только запоминает момент отката (для статистики) — а сам откат честно
 *    проигрывает физический движок через пакеты скорости сервера.
 */

/** Вешаем реакцию на урон. Вызывается из createBot. */
export function wireKnockback(bot: any): void {
  bot.on('entityHurt', (entity: any) => {
    if (entity && bot.entity && entity === bot.entity) {
      bot._lastKnockback = Date.now()
      // Намеренно ничего больше не делаем: не сбрасываем кнопки и не паузим.
      // Игрок не отпускает W оттого, что его ударили.
    }
  })
}

/** Сколько мс прошло с последнего отката (0 если откатов не было). */
export function sinceKnockback(bot: any): number {
  return bot._lastKnockback ? Date.now() - bot._lastKnockback : 0
}
